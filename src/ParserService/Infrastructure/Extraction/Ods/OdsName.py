    SPACES = f"{TEXT}s"
    TAB = f"{TEXT}tab"
    LINE_BREAK = f"{TEXT}line-break"
    STYLE_ELEMENT = f"{STYLE}style"
    TABLE_PROPERTIES = f"{STYLE}table-properties"
    SHEET_NAME = f"{TABLE}name"
    SHEET_STYLE = f"{TABLE}style-name"
    DISPLAY = f"{TABLE}display"
    ROWS_REPEATED = f"{TABLE}number-rows-repeated"
    COLUMNS_REPEATED = f"{TABLE}number-columns-repeated"
    ROWS_SPANNED = f"{TABLE}number-rows-spanned"
    COLUMNS_SPANNED = f"{TABLE}number-columns-spanned"
    FORMULA = f"{TABLE}formula"
    VALUE_TYPE = f"{OFFICE}value-type"
    VALUE = f"{OFFICE}value"
    DATE_VALUE = f"{OFFICE}date-value"
    TIME_VALUE = f"{OFFICE}time-value"
