from enum import StrEnum


class EnvironmentVariable(StrEnum):
    """Every environment variable the service reads. Nothing else is read from the environment.

    Values are documented in ``.env.example``; secrets never live in the repository.
    """

    DATABASE_URL = "PARSER_DATABASE_URL"
    ARTIFACT_ROOT = "PARSER_ARTIFACT_ROOT"
    LOG_LEVEL = "PARSER_LOG_LEVEL"
    HTTP_HOST = "PARSER_HTTP_HOST"
    HTTP_PORT = "PARSER_HTTP_PORT"
    MAX_FILE_SIZE_BYTES = "PARSER_MAX_FILE_SIZE_BYTES"
    MAX_PAGES = "PARSER_MAX_PAGES"
    JOB_TIMEOUT_SECONDS = "PARSER_JOB_TIMEOUT_SECONDS"
    JOB_MEMORY_LIMIT_MB = "PARSER_JOB_MEMORY_LIMIT_MB"
    ARCHIVE_MAX_DEPTH = "PARSER_ARCHIVE_MAX_DEPTH"
    ARCHIVE_MAX_FILES = "PARSER_ARCHIVE_MAX_FILES"
    ARCHIVE_MAX_EXPANDED_BYTES = "PARSER_ARCHIVE_MAX_EXPANDED_BYTES"
    MAX_ATTEMPTS = "PARSER_MAX_ATTEMPTS"
    QUEUE_CAPACITY = "PARSER_QUEUE_CAPACITY"
    RETENTION_DAYS = "PARSER_RETENTION_DAYS"
    MIN_FREE_DISK_BYTES = "PARSER_MIN_FREE_DISK_BYTES"
