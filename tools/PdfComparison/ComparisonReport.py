from collections.abc import Sequence
from typing import Final

from tools.PdfComparison.ComparisonResult import ComparisonResult


class ComparisonReport:
    """Renders the PDF library comparison as Markdown: measured results plus findings."""

    HEADER: Final = """# PDF library comparison (Phase 0)

Generated by `uv run python -m tools.PdfComparison docs/pdf-library-comparison.md`.
The script writes synthetic PDFs (a heading, 30 lines of text and a three-word table
row per page; no real data) with reportlab, then extracts every page with each
library. Time is the best of three runs on the machine that ran the script.

## Measured results

| Library | Pages | Time (ms) | Pages found | Word recall | Reading order |
|---|---|---|---|---|---|"""

    FINDINGS: Final = """
## What the libraries offer

| | pypdf | pdfplumber | pypdfium2 |
|---|---|---|---|
| Licence | BSD-3-Clause | MIT, needs Pillow (MIT-CMU) | Apache-2.0 / BSD-3-Clause |
| Implementation | Pure Python | Pure Python on pdfminer.six | Binding to Google's PDFium (C++) |
| Plain text per page | Yes | Yes | Yes |
| Character positions | Limited | Yes, per character and word | Yes, per character |
| Table detection | No | Yes (`extract_tables`) | No |
| Encrypted files | Detects, decrypts | Via pdfminer.six | Detects, opens |
| Renders pages to images (for OCR) | No | Via pypdfium2 | Yes |

## Findings

- All three recover every word in the right order on simple synthetic text, so
  accuracy does not separate them on this sample.
- Speed separates them clearly: pypdfium2 is the fastest by a wide margin, pypdf is
  several times slower, and pdfplumber is roughly two orders of magnitude slower
  because it builds a full layout model of every page.
- Only pdfplumber detects tables; only pypdfium2 renders pages, which the OCR
  path for scanned pages will need.

## Proposal for Phase 2 (for the lead to confirm)

1. **pypdfium2** as the main PDF extractor: page text, page count, character
   positions for locators, and page rendering for OCR.
2. **pdfplumber** only on pages where a table is likely, for table detection.
   Its dependency Pillow is licensed MIT-CMU, which is not on the brief's
   allow-list, so it needs the lead's approval before it becomes a runtime
   dependency.
3. **pypdf** as the fallback for broken files (repair attempts) and for clear
   password-protection errors.

## Limits of this comparison

The sample is single-column synthetic text. Phase 2 repeats the comparison on
multi-column layouts, real-looking tables, rotated pages and broken files from the
corpus before the choice is final.
"""

    def render(self, results: Sequence[ComparisonResult]) -> str:
        """Build the report.

        Args:
            results: Every measured result.

        Returns:
            The Markdown text.
        """
        rows = [self._row(result) for result in results]
        return "\n".join([self.HEADER, *rows]) + "\n" + self.FINDINGS

    @staticmethod
    def _row(result: ComparisonResult) -> str:
        cells = (
            result.library.value,
            str(result.page_count),
            f"{result.milliseconds:.1f}",
            str(result.pages_found),
            f"{result.word_recall:.1%}",
            f"{result.order_score:.1%}",
        )
        return f"| {' | '.join(cells)} |"
